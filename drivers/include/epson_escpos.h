/**
 * @brief   Device descriptor
 */
typedef struct {
    const epson_escpos_transport_t *transport;  /**< transport */
    void *transport_ctx;                        /**< transport context */
    const epson_escpos_profile_t *profile;      /**< printer profile */
    uint8_t buf[CONFIG_EPSON_ESCPOS_BUF_SIZE];  /**< transmit buffer */
    uint16_t buf_len;                           /**< bytes in the buffer */
    int8_t font;                                /**< current font, -1 if unknown */
    bool is_open;                               /**< connection is open */
} epson_escpos_t;

