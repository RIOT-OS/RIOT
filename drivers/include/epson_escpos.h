/**
 * @defgroup    drivers_epson_escpos Epson ESC/POS receipt printer
 * @ingroup     drivers_misc
 * @brief       Driver for Epson (and compatible) ESC/POS receipt printers
 *
 * This driver is a port of the Python library
 * [python-escpos](https://github.com/python-escpos/python-escpos).
 *
 * The driver is split into a transport independent core, which generates
 * the ESC/POS command stream, and one or more transports, which deliver the
 * byte stream to the printer. The following transports are available and
 * can be selected with the corresponding pseudomodules:
 *
 * | Module              | Transport                                  |
 * |---------------------|--------------------------------------------|
 * | `epson_escpos_tcp`  | TCP connection (raw port 9100) via `sock`  |
 * | `epson_escpos_uart` | Serial connection via `periph_uart`        |
 * | `epson_escpos_dummy`| Writes into a memory buffer (for testing)  |
 *
 * The `epson_escpos_tcp` driver uses lwIP4 as a backend, as the printers
 * available during development only support IPv4.
 *
 * Output is collected in a buffer inside the device descriptor and is only
 * sent to the printer when the buffer is full or when @ref epson_escpos_flush
 * is called. Commands that read from the printer (e.g. status queries) flush
 * the buffer automatically.
 *
 * ## Usage
 *
 * ```c
 * static epson_escpos_t dev;
 * static epson_escpos_tcp_t tcp;
 *
 * epson_escpos_tcp_setup(&tcp, &epson_escpos_tcp_params[0]);
 * epson_escpos_init(&dev, &epson_escpos_tcp_transport, &tcp,
 *                   &epson_escpos_profile_tm_t88iv);
 * epson_escpos_open(&dev);
 * epson_escpos_textln(&dev, "Hello RIOT!");
 * epson_escpos_cut(&dev, EPSON_ESCPOS_CUT_FULL, true);
 * epson_escpos_close(&dev);
 * ```
 *
 * ## Text encoding
 *
 * Text is sent to the printer as is, so it has to be encoded in the code page
 * selected with @ref epson_escpos_codepage. ASCII text works with all code
 * pages.
 *
 * @{
 *
 * @file
 * @brief       Public API of the Epson ESC/POS receipt printer driver
 *
 * @author      Christopher Büchse <christopher.buechse@tuhh.de>
 */

