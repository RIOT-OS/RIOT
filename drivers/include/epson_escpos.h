/**
 * @brief   Transport interface
 *
 * A transport delivers the generated byte stream to the printer. This is the
 * equivalent of the printer classes (`Network`, `Serial`, ...) in
 * python-escpos.
 */
typedef struct {
    /**
     * @brief   Open the connection to the printer
     *
     * @param[in] ctx   transport context
     *
     * @retval  0 on success
     * @retval  -errno on error
     */
    int (*open)(void *ctx);

    /**
     * @brief   Close the connection to the printer
     *
     * @param[in] ctx   transport context
     */
    void (*close)(void *ctx);

    /**
     * @brief   Write @p len bytes to the printer
     *
     * The function must only return after all data has been written.
     *
     * @param[in] ctx   transport context
     * @param[in] data  data to write
     * @param[in] len   number of bytes to write
     *
     * @retval  0 on success
     * @retval  -errno on error
     */
    int (*write)(void *ctx, const void *data, size_t len);

    /**
     * @brief   Read up to @p len bytes from the printer
     *
     * May be NULL if the transport does not support reading.
     *
     * @param[in]  ctx          transport context
     * @param[out] data         buffer for the received data
     * @param[in]  len          size of @p data
     * @param[in]  timeout_ms   timeout in milliseconds
     *
     * @return  number of bytes read on success
     * @retval  -ETIMEDOUT if nothing was received within @p timeout_ms
     * @retval  -errno on error
     */
    ssize_t (*read)(void *ctx, void *data, size_t len, uint32_t timeout_ms);
} epson_escpos_transport_t;

/**
 * @brief   Printer profile
 *
 * This is a small subset of the
 * [ESC/POS printer database](https://github.com/receipt-print-hq/escpos-printer-db)
 * used by python-escpos.
 */
typedef struct {
    const char *name;           /**< model name */
    uint8_t num_fonts;          /**< number of available fonts */
    uint8_t columns[2];         /**< characters per line for font A and B */
    bool full_cut;              /**< printer supports a full cut */
    bool part_cut;              /**< printer supports a partial cut */
} epson_escpos_profile_t;

