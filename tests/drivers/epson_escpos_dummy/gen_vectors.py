"""Generate the reference byte sequences in vectors.h with python-escpos.

Usage: gen_vectors.py

The script writes vectors.h next to itself. It needs python-escpos to be
installed, see README.md.

Every vector is the output of the python-escpos Dummy printer for the call
given in the table below. The test application performs the equivalent call
with the C driver and compares the output.

Deviations of the C driver from python-escpos are fixed up explicitly in
the FIXUPS table, so they are documented here.
"""

import os
import sys

if sys.version_info < (3, 11):
    sys.exit("python-escpos requires Python >= 3.11")

try:
    import escpos
    from escpos.printer import Dummy
except ImportError as e:
    sys.exit(f"python-escpos is not installed ({e}), see README.md")

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "vectors.h")

PROFILE = "TM-T88IV"

# name -> function calling python-escpos
VECTORS = {
    "align_center": lambda p: p.set(align="center"),
    "align_right": lambda p: p.set(align="right"),
    "bold_on": lambda p: p.set(bold=True),
    "underline_2": lambda p: p.set(underline=2),
    "size_2h": lambda p: p.set(double_height=True),
    "size_2w": lambda p: p.set(double_width=True),
    "size_2x": lambda p: p.set(double_width=True, double_height=True),
    "size_custom": lambda p: p.set(custom_size=True, width=3, height=2),
    "font_b": lambda p: p.set(font="b"),
    "density_0": lambda p: p.set(density=0),
    "density_5": lambda p: p.set(density=5),
    "invert_on": lambda p: p.set(invert=True),
    "smooth_on": lambda p: p.set(smooth=True),
    "flip_on": lambda p: p.set(flip=True),
    "set_combined": lambda p: p.set(align="center", bold=True, underline=1,
                                    double_height=True, font="b"),
    "set_default": lambda p: p.set_with_default(),
    "cut_full": lambda p: p.cut(),
    "cut_part": lambda p: p.cut(mode="PART"),
    "cut_part_nofeed": lambda p: p.cut(mode="PART", feed=False),
    "print_and_feed": lambda p: p.print_and_feed(3),
    "spacing_reset": lambda p: p.line_spacing(),
    "spacing_180": lambda p: p.line_spacing(30),
    "spacing_60": lambda p: p.line_spacing(30, divisor=60),
    "spacing_360": lambda p: p.line_spacing(200, divisor=360),
    "control_lf": lambda p: p.control("LF"),
    "control_ff": lambda p: p.control("FF"),
    "control_cr": lambda p: p.control("CR"),
    "control_vt": lambda p: p.control("VT"),
    "control_ht": lambda p: p.control("HT", count=5, tab_size=8),
    "hw_init": lambda p: p.hw("INIT"),
    "hw_select": lambda p: p.hw("SELECT"),
    "hw_reset": lambda p: p.hw("RESET"),
    "panel_buttons_off": lambda p: p.panel_buttons(False),
    "panel_buttons_on": lambda p: p.panel_buttons(True),
    "cashdraw_2": lambda p: p.cashdraw(2),
    "cashdraw_5": lambda p: p.cashdraw(5),
    "buzzer": lambda p: p.buzzer(3, 5),
    "print_speed": lambda p: p.set_print_speed(4),
    "textln": lambda p: p.textln("Hello RIOT"),
    "ln": lambda p: p.ln(3),
}

ESC_MODE_NORMAL = b"\x1b!\x00"


def _fix_size(data):
    # python-escpos sends ESC ! 0 three times before selecting the size
    # (TXT_NORMAL and the prefix of TXT_STYLE["size"]), the C driver only
    # sends the final ESC ! n
    while data.startswith(ESC_MODE_NORMAL * 2):
        data = data[len(ESC_MODE_NORMAL):]
    if data.startswith(ESC_MODE_NORMAL) and data[3:5] == b"\x1b!":
        data = data[len(ESC_MODE_NORMAL):]
    return data


def _fix_codepage(data):
    # python-escpos selects the code page (ESC t n) before the first text, the
    # C driver sends text as is
    assert data.startswith(b"\x1bt")
    return data[3:]


FIXUPS = {
    "size_2h": _fix_size,
    "size_2w": _fix_size,
    "size_2x": _fix_size,
    "set_combined": _fix_size,
    "set_default": _fix_size,
    "textln": _fix_codepage,
    "ln": _fix_codepage,
}


def main():
    lines = [
        "/*",
        " * SPDX-FileCopyrightText: escpos-printer-db contributors",
        " * SPDX-FileCopyrightText: 2026 The RIOT Contributors",
        " * SPDX-License-Identifier: LGPL-2.1-only",
        " */",
        "",
        "/* generated by gen_vectors.py from python-escpos "
        f"{escpos.__version__}, do not edit */",
        "",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        "extern \"C\" {",
        "#endif",
        "",
    ]
    for name, func in VECTORS.items():
        p = Dummy(profile=PROFILE)
        func(p)
        data = p.output
        if name in FIXUPS:
            data = FIXUPS[name](data)
        lines.append(f"static const uint8_t vec_{name}[] = {{")
        for i in range(0, len(data), 12):
            chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 12])
            lines.append(f"    {chunk},")
        lines += ["};", ""]
    lines += [
        "#ifdef __cplusplus",
        "}",
        "#endif",
    ]

    # only written after all vectors were generated successfully
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
